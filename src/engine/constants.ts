export function getSkyBrightness(timeOfDay: number): number {
  const t = ((timeOfDay % DAY_CYCLE_SECONDS) + DAY_CYCLE_SECONDS) % DAY_CYCLE_SECONDS;
  if (t < DAY_DURATION) return 1.0;
  if (t < DAY_DURATION + SUNSET_DURATION) {
    const p = (t - DAY_DURATION) / SUNSET_DURATION;
    return 1.0 - p * 0.9;
  }
  if (t < DAY_DURATION + SUNSET_DURATION + NIGHT_DURATION) {
    return 0.1;
  }
  const p = (t - (DAY_DURATION + SUNSET_DURATION + NIGHT_DURATION)) / SUNRISE_DURATION;
  return 0.1 + p * 0.9;
}

export function isNightTime(timeOfDay: number): boolean {
  const t = ((timeOfDay % DAY_CYCLE_SECONDS) + DAY_CYCLE_SECONDS) % DAY_CYCLE_SECONDS;
  return t >= DAY_DURATION + SUNSET_DURATION * 0.5 && t <= DAY_DURATION + SUNSET_DURATION + NIGHT_DURATION + SUNRISE_DURATION * 0.4;
}
